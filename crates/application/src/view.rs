pub fn project(
    room: &WarRoom,
    summaries: &HashMap<SessionId, TranscriptSummary>,
    approvable: &HashSet<SessionId>,
    now: Timestamp,
) -> WarRoomView {
    let mut by_repo: BTreeMap<String, RoomView> = BTreeMap::new();
    for session in room.sessions() {
        let entry = by_repo.entry(session.workspace.repo.0.clone()).or_insert_with(|| RoomView {
            repo_id: session.workspace.repo.0.clone(),
            repo_name: session.workspace.repo_name.clone(),
            attention: AttentionView::Offline,
            sessions: Vec::new(),
        });
        entry.sessions.push(session_view(session, summaries.get(&session.id), approvable.contains(&session.id), now));
    }

    let mut rooms: Vec<RoomView> = by_repo
        .into_values()
        .map(|mut r| {
            r.sessions.sort_by_key(|s| (std::cmp::Reverse(s.attention), std::cmp::Reverse(s.last_activity_at)));
            r.attention = r
                .sessions
                .iter()
                .filter(|s| !s.archived && !s.muted)
                .map(|s| s.attention)
                .max()
                .unwrap_or(AttentionView::Offline);
            r
        })
        .collect();
    rooms.sort_by(|a, b| b.attention.cmp(&a.attention).then_with(|| a.repo_name.cmp(&b.repo_name)));

    let mut today = Usage::default();
    for summary in summaries.values() {
        today.add(&summary.usage_today);
    }
    WarRoomView { aggregate: room.aggregate_attention().into(), rooms, today: (&today).into() }
}

/// When a working session went silent, if it has been silent long enough to look stuck.
pub fn stalled_since(s: &Session, now: Timestamp) -> Option<i64> {
    let working = matches!(s.status, SessionStatus::Working { .. } | SessionStatus::Compacting);
    (working && now.0 - s.last_activity_at.0 >= STALL_AFTER_MS).then_some(s.last_activity_at.0)
}

pub(crate) fn session_view(
    s: &Session,
    summary: Option<&TranscriptSummary>,
    can_approve: bool,
    now: Timestamp,
) -> SessionView {
    let summary = summary.cloned().unwrap_or_default();
    let detail = |id: &str| summary.subagents.iter().find(|d| d.id == id).cloned().unwrap_or_default();
    let mut view = SessionView {
        id: s.id.0.clone(),
        provider: format!("{:?}", s.provider).to_lowercase(),
        attention: s.attention().into(),
        status_label: status_label(s),
        title: summary.title.clone(),
        first_prompt: summary.first_prompt.clone(),
        command: s.host.agent_command.as_deref().map(readable_command),
        last_prompt: summary.last_prompt.clone(),
        last_reply: summary.last_reply.clone(),
        last_action: summary.last_action.clone(),
        model: summary.model.clone(),
        effort: summary.effort.clone(),
        context_tokens: summary.context_tokens,
        context_window: summary.context_window,
        usage: (&summary.usage).into(),
        stalled_since: stalled_since(s, now),
        worktree_path: s.workspace.worktree_path.clone(),
        branch: s.workspace.branch.clone(),
        is_linked_worktree: s.workspace.is_linked_worktree,
        subagents: s
            .subagents
            .values()
            .map(|a| {
                let d = detail(&a.id);
                SubagentView {
                    id: a.id.clone(),
                    kind: a.kind.clone(),
                    description: d.description,
                    // The transcript gives more detail ("Grep · pattern"); the hook, at least the name.
                    last_tool: d.last_tool.or_else(|| a.current_tool.clone()),
                    model: d.model,
                    effort: d.effort,
                    running: a.is_running(),
                    started_at: a.started_at.0,
                    finished_at: a.finished_at.map(|t| t.0),
                }
            })
            .collect(),
        skills: {
            let mut skills: Vec<SkillView> = s
                .skills
                .values()
                .map(|k| SkillView {
                    name: k.name.clone(),
                    source: k.source.into(),
                    by_user: k.by_user,
                    by_agent: k.by_agent,
                    count: k.count,
                    last_at: k.last_at.0,
                })
                .collect();
            skills.sort_by_key(|k| std::cmp::Reverse(k.last_at));
            skills
        },
        turns: s.turns,
        started_at: s.started_at.0,
        last_activity_at: s.last_activity_at.0,
        status_since: s.status_since.0,
        archived: s.archived,
        muted: s.muted,
        alive: s.is_alive(),
        terminal: terminal_name(s),
        tmux_pane: s.host.tmux_pane.clone(),
        in_warp: s.host.warp_focus_url.is_some(),
        pty_id: s.host.pty_id.clone(),
        can_approve,
    };
    // Running ones first; within each group, in order of arrival.
    view.subagents.sort_by_key(|a| (!a.running, a.started_at));
    view
}

fn status_label(s: &Session) -> String {
    match &s.status {
        SessionStatus::Idle => locale::status_idle().into(),
        SessionStatus::Working { tool: Some(tool) } => tool.clone(),
        SessionStatus::Working { tool: None } => locale::status_thinking().into(),
        SessionStatus::AwaitingYou { reason: WaitReason::Permission, tool, detail } => match (tool, detail) {
            (Some(tool), Some(detail)) => locale::asks_permission_for_detail(tool, detail),
            (Some(tool), None) => locale::asks_permission_for(tool),
            _ => locale::status_asks_permission().into(),
        },
        SessionStatus::AwaitingYou { reason: WaitReason::Question, .. } => locale::status_asks_question().into(),
        SessionStatus::AwaitingInput if s.unseen => locale::status_finished().into(),
        SessionStatus::AwaitingInput => locale::status_your_turn().into(),
        SessionStatus::Compacting => locale::status_compacting().into(),
        SessionStatus::Ended { .. } => locale::status_ended().into(),
    }
}

/// First ancestor of the agent that looks like a terminal or IDE (what needs focusing).
/// The command as you would type it: `/…/vendor/…/bin/codex resume x` → `codex resume x`.
fn readable_command(command: &str) -> String {
    let (program, args) = command.split_once(' ').unwrap_or((command, ""));
    let program = program.rsplit('/').next().unwrap_or(program);
    if args.is_empty() { program.to_owned() } else { format!("{program} {args}") }
}

fn terminal_name(s: &Session) -> Option<String> {
    if let Some(program) = &s.host.term_program {
        return Some(program.clone());
    }
    const SHELLS: &[&str] = &["bash", "zsh", "fish", "sh", "dash", "claude", "node", "tmux: server", "tmux"];
    let agent = s.host.agent_pid?;
    s.host
        .ancestry
        .iter()
        .skip_while(|p| p.pid != agent)
        .skip(1)
        .find(|p| !SHELLS.contains(&p.name.as_str()))
        .map(|p| p.name.clone())
}

