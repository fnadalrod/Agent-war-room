/// Same urgency order as `Attention`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Serialize, TS)]
#[serde(rename_all = "snake_case")]
#[ts(export)]
pub enum AttentionView {
    Offline,
    Idle,
    Working,
    Finished,
    NeedsYou,
}

impl From<Attention> for AttentionView {
    fn from(a: Attention) -> Self {
        match a {
            Attention::Offline => Self::Offline,
            Attention::Idle => Self::Idle,
            Attention::Working => Self::Working,
            Attention::Finished => Self::Finished,
            Attention::NeedsYou => Self::NeedsYou,
        }
    }
}

#[derive(Debug, Clone, PartialEq, Serialize, TS)]
#[ts(export)]
pub struct WarRoomView {
    pub aggregate: AttentionView,
    pub rooms: Vec<RoomView>,
    /// Tokens and estimated cost of every known session today.
    pub today: UsageView,
}

/// A working session with no activity for this long is flagged as possibly stuck.
pub const STALL_AFTER_MS: i64 = 6 * 60 * 1000;

/// While a shell command runs, silence is expected (builds, test suites), so it waits longer.
pub const COMMAND_STALL_AFTER_MS: i64 = 30 * 60 * 1000;

/// Shell tool names as each provider reports them in its hooks.
const SHELL_TOOLS: &[&str] = &["Bash", "Shell", "PowerShell", "run_command"];

#[derive(Debug, Clone, Copy, Default, PartialEq, Serialize, TS)]
#[ts(export)]
pub struct UsageView {
    #[ts(type = "number")]
    pub input_tokens: u64,
    #[ts(type = "number")]
    pub output_tokens: u64,
    #[ts(type = "number")]
    pub cache_read_tokens: u64,
    #[ts(type = "number")]
    pub cache_write_tokens: u64,
    #[ts(type = "number")]
    pub total_tokens: u64,
    /// Estimated at API prices; subscriptions don't pay this, but it compares sessions.
    pub cost_usd: f64,
    /// Some messages used a model without a known price.
    pub partial_cost: bool,
}

impl From<&Usage> for UsageView {
    fn from(u: &Usage) -> Self {
        Self {
            input_tokens: u.input_tokens,
            output_tokens: u.output_tokens,
            cache_read_tokens: u.cache_read_tokens,
            cache_write_tokens: u.cache_write_tokens,
            total_tokens: u.tokens(),
            cost_usd: u.cost_micros as f64 / 1_000_000.0,
            partial_cost: u.unpriced_messages > 0,
        }
    }
}

