pub fn project(
    room: &WarRoom,
    summaries: &HashMap<SessionId, TranscriptSummary>,
    approvable: &HashSet<SessionId>,
    now: Timestamp,
) -> WarRoomView {
    let mut by_repo: BTreeMap<String, RoomView> = BTreeMap::new();
    for session in room.sessions() {
        let entry = by_repo.entry(session.workspace.repo.0.clone()).or_insert_with(|| RoomView {
            repo_id: session.workspace.repo.0.clone(),
            repo_name: session.workspace.repo_name.clone(),
            attention: AttentionView::Offline,
            sessions: Vec::new(),
        });
        entry.sessions.push(session_view(session, summaries.get(&session.id), approvable.contains(&session.id), now));
    }
    let mut shared = shared_files(room, summaries);
    for view in by_repo.values_mut().flat_map(|r| r.sessions.iter_mut()) {
        view.shared_files = shared.remove(&SessionId(view.id.clone())).unwrap_or_default();
    }

    let mut rooms: Vec<RoomView> = by_repo
        .into_values()
        .map(|mut r| {
            r.sessions.sort_by_key(|s| (std::cmp::Reverse(s.attention), std::cmp::Reverse(s.last_activity_at)));
            r.attention = r
                .sessions
                .iter()
                .filter(|s| !s.archived && !s.muted)
                .map(|s| s.attention)
                .max()
                .unwrap_or(AttentionView::Offline);
            r
        })
        .collect();
    rooms.sort_by(|a, b| b.attention.cmp(&a.attention).then_with(|| a.repo_name.cmp(&b.repo_name)));

    let mut today = Usage::default();
    for summary in summaries.values() {
        today.add(&summary.usage_today);
    }
    let aggregate = rooms.iter().map(|r| r.attention).max().unwrap_or(AttentionView::Offline);
    WarRoomView { aggregate, rooms, today: (&today).into() }
}

/// Files edited by more than one live, not archived session of the same worktree, per session.
/// Separate worktrees never clash: that is the way out this nudges towards.
pub(crate) fn shared_files(
    room: &WarRoom,
    summaries: &HashMap<SessionId, TranscriptSummary>,
) -> HashMap<SessionId, Vec<SharedFileView>> {
    // (worktree, absolute path) → sessions that edited it.
    let mut editors: BTreeMap<(&str, String), Vec<&SessionId>> = BTreeMap::new();
    for s in room.sessions().filter(|s| s.is_alive() && !s.archived) {
        let worktree = s.workspace.worktree_path.as_str();
        for file in summaries.get(&s.id).into_iter().flat_map(|x| &x.edited_files) {
            let absolute = if file.starts_with('/') { file.clone() } else { format!("{worktree}/{file}") };
            editors.entry((worktree, absolute)).or_default().push(&s.id);
        }
    }
    let mut out: HashMap<SessionId, Vec<SharedFileView>> = HashMap::new();
    for ((worktree, file), ids) in editors.into_iter().filter(|(_, ids)| ids.len() > 1) {
        let path = file.strip_prefix(worktree).and_then(|p| p.strip_prefix('/')).unwrap_or(&file).to_owned();
        for id in &ids {
            let sessions = ids.iter().filter(|o| o != &id).map(|o| o.0.clone()).collect();
            out.entry((*id).clone()).or_default().push(SharedFileView { path: path.clone(), sessions });
        }
    }
    out
}

/// A completed main turn still owns any commands running in the background.
pub(crate) fn effective_attention(s: &Session, summary: Option<&TranscriptSummary>) -> Attention {
    let attention = s.attention();
    if matches!(s.status, SessionStatus::AwaitingYou { reason: WaitReason::Permission, .. })
        && summary.is_some_and(|s| s.automatic_permission_review)
    {
        return Attention::Working;
    }
    if matches!(attention, Attention::Idle | Attention::Finished)
        && summary.is_some_and(|summary| summary.running_commands > 0)
    {
        Attention::Working
    } else {
        attention
    }
}

/// When a working session went silent, if it has been silent long enough to look stuck.
pub fn stalled_since(s: &Session, now: Timestamp) -> Option<i64> {
    let after = match &s.status {
        SessionStatus::Working { tool: Some(tool) } if SHELL_TOOLS.contains(&tool.as_str()) => COMMAND_STALL_AFTER_MS,
        SessionStatus::Working { .. } | SessionStatus::Compacting => STALL_AFTER_MS,
        _ => return None,
    };
    (now.0 - s.last_activity_at.0 >= after).then_some(s.last_activity_at.0)
}

pub(crate) fn session_view(
    s: &Session,
    summary: Option<&TranscriptSummary>,
    can_approve: bool,
    now: Timestamp,
) -> SessionView {
    let summary = summary.cloned().unwrap_or_default();
    let detail = |id: &str| summary.subagents.iter().find(|d| d.id == id).cloned().unwrap_or_default();
    let (awaiting_question, pending_question) = match &s.status {
        SessionStatus::AwaitingYou { reason: WaitReason::Question, detail, .. } => (true, detail.clone()),
        _ => (false, None),
    };
    let mut view = SessionView {
        id: s.id.0.clone(),
        provider: format!("{:?}", s.provider).to_lowercase(),
        attention: effective_attention(s, Some(&summary)).into(),
        status_label: if effective_attention(s, Some(&summary)) == Attention::Working
            && matches!(
                s.status,
                SessionStatus::Idle | SessionStatus::AwaitingInput | SessionStatus::AwaitingYou { .. }
            ) {
            locale::status_thinking().into()
        } else {
            status_label(s)
        },
        title: summary.title.clone(),
        first_prompt: summary.first_prompt.clone(),
        command: s.host.agent_command.as_deref().map(readable_command),
        last_prompt: summary.last_prompt.clone(),
        last_reply: summary.last_reply.clone(),
        last_action: summary.last_action.clone(),
        model: summary.model.clone(),
        effort: summary.effort.clone(),
        context_tokens: summary.context_tokens,
        context_window: summary.context_window,
        usage: (&summary.usage).into(),
        stalled_since: stalled_since(s, now),
        worktree_path: s.workspace.worktree_path.clone(),
        branch: s.workspace.branch.clone(),
        is_linked_worktree: s.workspace.is_linked_worktree,
        subagents: s
            .subagents
            .values()
            .map(|a| {
                let d = detail(&a.id);
                SubagentView {
                    id: a.id.clone(),
                    kind: a.kind.clone(),
                    description: d.description,
                    // The transcript gives more detail ("Grep · pattern"); the hook, at least the name.
                    last_tool: d.last_tool.or_else(|| a.current_tool.clone()),
                    model: d.model,
                    effort: d.effort,
                    running: a.is_running(),
                    started_at: a.started_at.0,
                    finished_at: a.finished_at.map(|t| t.0),
                }
            })
            .collect(),
        skills: {
            let mut skills: Vec<SkillView> = s
                .skills
                .values()
                .map(|k| SkillView {
                    name: k.name.clone(),
                    source: k.source.into(),
                    by_user: k.by_user,
                    by_agent: k.by_agent,
                    count: k.count,
                    last_at: k.last_at.0,
                })
                .collect();
            skills.sort_by_key(|k| std::cmp::Reverse(k.last_at));
            skills
        },
        turns: s.turns,
        started_at: s.started_at.0,
        last_activity_at: s.last_activity_at.0,
        status_since: s.status_since.0,
        archived: s.archived,
        muted: s.muted,
        alive: s.is_alive(),
        terminal: terminal_name(s),
        tmux_pane: s.host.tmux_pane.clone(),
        in_warp: s.host.warp_focus_url.is_some(),
        pty_id: s.host.pty_id.clone(),
        can_approve,
        awaiting_question,
        pending_question,
        can_answer_question: false,
        questions: Vec::new(),
        shared_files: Vec::new(),
    };
    // Running ones first; within each group, in order of arrival.
    view.subagents.sort_by_key(|a| (!a.running, a.started_at));
    view
}

fn status_label(s: &Session) -> String {
    match &s.status {
        SessionStatus::Idle | SessionStatus::AwaitingInput if s.running_subagents() > 0 => {
            locale::status_thinking().into()
        }
        SessionStatus::Idle => locale::status_idle().into(),
        SessionStatus::Working { tool: Some(tool) } => tool.clone(),
        SessionStatus::Working { tool: None } => locale::status_thinking().into(),
        SessionStatus::AwaitingYou { reason: WaitReason::Permission, tool, detail } => match (tool, detail) {
            (Some(tool), Some(detail)) => locale::asks_permission_for_detail(tool, detail),
            (Some(tool), None) => locale::asks_permission_for(tool),
            _ => locale::status_asks_permission().into(),
        },
        SessionStatus::AwaitingYou { reason: WaitReason::Question, .. } => locale::status_asks_question().into(),
        SessionStatus::AwaitingInput if s.unseen => locale::status_finished().into(),
        SessionStatus::AwaitingInput => locale::status_your_turn().into(),
        SessionStatus::Compacting => locale::status_compacting().into(),
        SessionStatus::Ended { .. } => locale::status_ended().into(),
    }
}

/// First ancestor of the agent that looks like a terminal or IDE (what needs focusing).
/// The command as you would type it: `/…/vendor/…/bin/codex resume x` → `codex resume x`.
fn readable_command(command: &str) -> String {
    let (program, args) = command.split_once(' ').unwrap_or((command, ""));
    let program = program.rsplit('/').next().unwrap_or(program);
    if args.is_empty() { program.to_owned() } else { format!("{program} {args}") }
}

fn terminal_name(s: &Session) -> Option<String> {
    if let Some(program) = &s.host.term_program {
        return Some(program.clone());
    }
    const SHELLS: &[&str] = &["bash", "zsh", "fish", "sh", "dash", "claude", "node", "tmux: server", "tmux"];
    let agent = s.host.agent_pid?;
    s.host
        .ancestry
        .iter()
        .skip_while(|p| p.pid != agent)
        .skip(1)
        .find(|p| !SHELLS.contains(&p.name.as_str()))
        .map(|p| p.name.clone())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn launch_commands_read_as_typed() {
        assert_eq!(
            readable_command("/home/u/.npm/vendor/x86_64/bin/codex --sandbox read-only"),
            "codex --sandbox read-only"
        );
        assert_eq!(readable_command("claude"), "claude");
    }

    #[test]
    fn a_running_shell_command_gets_longer_before_it_looks_stuck() {
        use awr_domain::{ProviderKind, RepoId, SessionContext, SessionEventKind, TerminalHost, Workspace};
        let context = SessionContext {
            provider: ProviderKind::Claude,
            workspace: Workspace {
                repo: RepoId("/repo/.git".into()),
                repo_name: "repo".into(),
                worktree_path: "/repo".into(),
                branch: None,
                is_linked_worktree: false,
            },
            host: TerminalHost::default(),
            transcript_path: None,
            cwd: None,
        };
        let mut s = Session::open(SessionId("s".into()), context, Timestamp(0));
        let after = |s: &Session, ms: i64| stalled_since(s, Timestamp(ms)).is_some();

        s.apply(None, &SessionEventKind::ToolStarted { tool: "Read".into() }, Timestamp(0));
        assert!(after(&s, STALL_AFTER_MS));

        s.apply(None, &SessionEventKind::ToolStarted { tool: "Bash".into() }, Timestamp(0));
        assert!(!after(&s, STALL_AFTER_MS), "a build or a test suite can be silent for a while");
        assert!(after(&s, COMMAND_STALL_AFTER_MS));

        s.apply(None, &SessionEventKind::ToolFinished { tool: "Bash".into(), failed: false }, Timestamp(0));
        assert!(after(&s, STALL_AFTER_MS), "thinking after the command uses the normal threshold");
    }
}
