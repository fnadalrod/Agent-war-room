#[derive(Debug, Clone, PartialEq, Serialize, TS)]
#[ts(export)]
pub struct SessionView {
    pub id: String,
    pub provider: String,
    pub attention: AttentionView,
    /// Short on-screen phrase (UI copy): the current tool, a permission request, "your turn"…
    pub status_label: String,
    /// Title generated by the agent; `null` until it writes one.
    pub title: Option<String>,
    /// The task the session started with.
    pub first_prompt: Option<String>,
    /// How the agent was launched (`claude --resume …`).
    pub command: Option<String>,
    pub last_prompt: Option<String>,
    pub last_reply: Option<String>,
    pub last_action: Option<String>,
    pub model: Option<String>,
    /// Reasoning effort of the last turn.
    pub effort: Option<String>,
    #[ts(type = "number | null")]
    pub context_tokens: Option<u64>,
    /// Context window of the current model, to show how full it is.
    #[ts(type = "number | null")]
    pub context_window: Option<u64>,
    pub usage: UsageView,
    /// Working but silent since this moment (ms) for longer than [`STALL_AFTER_MS`]: maybe stuck.
    #[ts(type = "number | null")]
    pub stalled_since: Option<i64>,
    pub worktree_path: String,
    pub branch: Option<String>,
    pub is_linked_worktree: bool,
    pub subagents: Vec<SubagentView>,
    /// Skills used, most recent first.
    pub skills: Vec<SkillView>,
    pub turns: u32,
    #[ts(type = "number")]
    pub started_at: i64,
    #[ts(type = "number")]
    pub last_activity_at: i64,
    #[ts(type = "number")]
    pub status_since: i64,
    pub archived: bool,
    pub muted: bool,
    pub alive: bool,
    pub terminal: Option<String>,
    pub tmux_pane: Option<String>,
    /// There is a direct link to the Warp pane.
    pub in_warp: bool,
    /// The app's own terminal: can be viewed and typed into from here.
    pub pty_id: Option<String>,
    /// There is a pending permission that can be approved or denied from the app.
    pub can_approve: bool,
}

